export const productsBySlug = Object.fromEntries(products.map((product) => [product.slug, product]));

export function validateProducts(records = products) {
  const errors = [];
  const asins = new Set();
  const slugs = new Set();
  for (const product of records) {
    if (!product.slug || slugs.has(product.slug)) errors.push(`Duplicate or missing slug: ${product.slug || "(missing)"}`);
    slugs.add(product.slug);
    if (!product.affiliateUrl) errors.push(`${product.slug}: missing affiliateUrl`);
    else {
      try {
        const url = new URL(product.affiliateUrl);
        if (!["amazon.com", "www.amazon.com", "amzn.to"].includes(url.hostname)) errors.push(`${product.slug}: unsupported affiliate host`);
      } catch { errors.push(`${product.slug}: invalid affiliateUrl`); }
    }
    if (product.asin) {
      if (asins.has(product.asin)) errors.push(`${product.slug}: duplicate ASIN ${product.asin}`);
      asins.add(product.asin);
    }
    if (!product.imageAlt?.trim()) errors.push(`${product.slug}: missing imageAlt`);
    if (!product.sourceUrl) errors.push(`${product.slug}: missing sourceUrl`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(product.dateChecked || "")) errors.push(`${product.slug}: invalid dateChecked`);
  }
  return errors;
}
